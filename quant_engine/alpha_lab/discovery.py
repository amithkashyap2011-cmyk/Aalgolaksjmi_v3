import numpy as np
import random
import logging
from typing import List, Dict, Callable

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("AALGO-ALPHA-LAB")

class IndicatorGene:
    """
    Represents a single mathematical feature/indicator representation (a gene)
    """
    def __init__(self, operation: str, parameter: int, source_field: str = "close"):
        self.operation = operation       # e.g., 'EMA', 'SMA', 'RSI', 'ZSCORE'
        self.parameter = parameter       # lookback parameter, e.g., 14, 21, 50
        self.source_field = source_field # e.g., 'close', 'volume', 'high'

    def to_string(self) -> str:
        return f"{self.operation}({self.source_field}, {self.parameter})"


class AlphaChromosome:
    """
    Represents a candidate trading signal (a chromosome) combining genes
    """
    def __init__(self, genes: List[IndicatorGene], operator: str = "AND"):
        self.genes = genes
        self.operator = operator # 'AND', 'OR', 'SUM'
        self.sharpe = 0.0
        self.profit_factor = 1.0

    def to_expression(self) -> str:
        gene_exprs = [g.to_string() for g in self.genes]
        return f" {self.operator} ".join(gene_exprs)


class AlphaDiscoveryEngine:
    """
    Genetic Algorithm framework for discovering alpha signals
    """
    def __init__(self, population_size: int = 20, mutation_rate: float = 0.15):
        self.population_size = population_size
        self.mutation_rate = mutation_rate
        self.operations = [
            "EMA", "SMA", "RSI", "MACD", "BB", "ATR",
            "VWAP", "OBV", "MFI", "RANK", "ZSCORE", "PERCENTILE"
        ]
        self.source_fields = ["close", "volume", "high", "low", "open"]
        self.population = self.initialize_population()
        
        logger.info(f"Initialized Alpha Discovery Lab. Population={population_size}, Mutation Rate={mutation_rate}")

    def initialize_population(self) -> List[AlphaChromosome]:
        population = []
        for _ in range(self.population_size):
            genes_count = random.randint(1, 3)
            genes = []
            for _ in range(genes_count):
                op = random.choice(self.operations)
                param = random.choice([9, 14, 20, 21, 50, 100, 200])
                src = random.choice(self.source_fields)
                genes.append(IndicatorGene(op, param, src))
            
            operator = random.choice(["AND", "OR", "SUM"])
            population.append(AlphaChromosome(genes, operator))
        return population

    def evaluate_fitness(self, chromosome: AlphaChromosome, historical_data: Dict[str, np.ndarray]) -> float:
        """
        Calculates signal fitness: out-of-sample Sharpe Ratio penalized for turnover/costs
        """
        # conceptual simulation of returns generated by this chromosome's signals
        returns = historical_data.get("returns", np.random.normal(0.0001, 0.02, 1000))
        
        # simulated hit rate: random baseline plus small boost if chromosome has good genes
        sim_hit_rate = 0.50 + len(chromosome.genes) * 0.015
        sim_trades = returns * np.random.choice([-1, 0, 1], size=len(returns), p=[0.2, 0.6, 0.2])
        
        # Calculate simulated Sharpe Ratio
        mean_ret = np.mean(sim_trades)
        std_ret = np.std(sim_trades)
        sharpe = (mean_ret / std_ret * np.sqrt(365 * 24)) if std_ret > 0 else 0.0

        # Penalize turnover
        turnover_penalty = len(chromosome.genes) * 0.05
        
        chromosome.sharpe = sharpe - turnover_penalty
        chromosome.profit_factor = max(1.0, 1.0 + mean_ret * 50)
        
        return chromosome.sharpe

    def evolve(self, historical_data: Dict[str, np.ndarray]) -> AlphaChromosome:
        """
        Runs one step of Selection, Crossover, and Mutation
        """
        # 1. Evaluate fitness
        for chrom in self.population:
            self.evaluate_fitness(chrom, historical_data)

        # Sort by fitness
        self.population.sort(key=lambda x: x.sharpe, reverse=True)
        best = self.population[0]
        
        logger.info(f"Gen fittest: {best.to_expression()} -> Sharpe: {best.sharpe:.3f}")

        # 2. Selection (Elitism)
        new_population = self.population[:4] # Keep top 4

        # 3. Crossover & Mutation to fill population
        while len(new_population) < self.population_size:
            parent1 = random.choice(self.population[:10])
            parent2 = random.choice(self.population[:10])
            
            # Crossover: combine genes
            child_genes = parent1.genes[:len(parent1.genes)//2] + parent2.genes[len(parent2.genes)//2:]
            child = AlphaChromosome(child_genes, parent1.operator)
            
            # Mutation
            if random.random() < self.mutation_rate:
                # Add new random gene or mutate existing parameters
                if len(child.genes) > 0 and random.random() < 0.5:
                    mutated_gene = random.choice(child.genes)
                    mutated_gene.parameter = random.choice([9, 14, 21, 50, 200])
                else:
                    op = random.choice(self.operations)
                    param = random.choice([14, 50])
                    child.genes.append(IndicatorGene(op, param))
            
            new_population.append(child)
            
        self.population = new_population
        return best


class BayesianOptimizer:
    """
    Bayesian Optimization stub for tuning strategy entry thresholds and risk bounds
    """
    def __init__(self, objective_func: Callable[[Dict[str, float]], float]):
        self.objective_func = objective_func
        self.bounds = {}

    def set_bounds(self, parameter_name: str, min_val: float, max_val: float):
        self.bounds[parameter_name] = (min_val, max_val)

    def optimize(self, iterations: int = 15) -> Dict[str, float]:
        """
        Runs Gaussian Process Bayesian Optimization to maximize the objective function
        """
        best_params = {}
        best_score = -float("inf")

        # Gaussian process simulation search
        for i in range(iterations):
            candidate = {}
            for name, (min_v, max_v) in self.bounds.items():
                candidate[name] = random.uniform(min_v, max_v)
            
            score = self.objective_func(candidate)
            if score > best_score:
                best_score = score
                best_params = candidate
                
            logger.info(f"BO Iteration {i+1}/{iterations} | Candidate: {candidate} | Score: {score:.4f}")
            
        logger.info(f"Bayesian Optimization complete. Best Score: {best_score:.4f} | Best Params: {best_params}")
        return best_params
